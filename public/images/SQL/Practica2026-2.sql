/*1.Mostrar el nombre, el apellido, el salario, el ID del departamento y el nombre de la región 
de todos los empleados que pertenecen a los departamentos con identificador 80 o 90.*/

SELECT E.FIRST_NAME,
       E.LAST_NAME,
       E.SALARY,
       D.DEPARTMENT_ID,
       R.REGION_NAME
     
FROM HR.EMPLOYEES E
LEFT JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
LEFT JOIN HR.COUNTRIES C
ON L.COUNTRY_ID = C.COUNTRY_ID
LEFT JOIN HR.REGIONS R
ON C.REGION_ID = R.REGION_ID
WHERE D.DEPARTMENT_ID IN (80,90) ;




//2.MOSTRAR LOS NOMBRES Y APELLIDO CONCATENADO EN UNA COLUMNA Y MOSTRAR LOS NOMBRES Y APELLIDOS

SELECT 
    e.first_name || ' ' || e.last_name AS "Empleado",
    m.first_name || ' ' || m.last_name AS "Manager"
FROM hr.employees e
LEFT JOIN hr.employees m
    ON e.manager_id = m.employee_id;

/*3.MOSTRAR CUANTOS EMPLEADOS HAY POR PAIS NOMBRE PAIS CANTIDAD DE EMPLEADOS PERO SOLO MOSTRAR LOS PAISES QUE TENGAN MAS DE 10 EMPLEADOS*/
SELECT C.COUNTRY_NAME AS "NOMBRE PAIS",
       COUNT(E.EMPLOYEE_ID) AS "CANTIDAD EMPLEADOS"
FROM HR.EMPLOYEES E 
INNER JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
INNER JOIN HR.LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID
INNER JOIN HR.COUNTRIES C
    ON L.COUNTRY_ID = C.COUNTRY_ID
GROUP BY C.COUNTRY_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 10;

/*4.MOSTRAR NOMBRE DE DEPARTAMENTO Y SUMA DE LA CANTIDAD DE SUS SALARIOS PERO ORDENARLO DEL MAYOR A MENOR
SALARIO SOLO TRAER LOS 5 PRIMEROS DEPARTAMENTOS SI EN LA POSICION NUMERO 5 HAY UN EMPATE DEBE MOSTRAR TODOS LOS REGISTROS  */

SELECT 
    D.DEPARTMENT_NAME AS "DEPARTAMENTO",
    SUM(E.SALARY) AS "SUMA DE SALARIOS"
FROM HR.DEPARTMENTS D
JOIN HR.EMPLOYEES E 
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY SUM(E.SALARY) DESC
FETCH FIRST 5 ROWS WITH TIES;


/*5.BUSCAR TODOS LOS EMPLEADOS QUE HAN TENIDO MAS DE DOS CARGOS EN LA COMPAÑIA,APARTE DEL CARGO QUE TIENEN ACTUALMENTE
NOMBRE Y CANTIDAD DE CARGOS*/

SELECT E.FIRST_NAME, 
       COUNT(JH.JOB_ID) AS CANTIDAD_CARGOS
FROM HR.EMPLOYEES E
INNER JOIN HR.JOB_HISTORY JH
    ON E.EMPLOYEE_ID = JH.EMPLOYEE_ID
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME
HAVING COUNT(JH.JOB_ID) > 2;



/*6.BUSCAR TODOS LOS EMPLEADOS QUE PERTENEZCAN AL REINO UNIDO
PERO QUE EN EL NOMBRE EN LA TERCERA POCISION TENGA UNA A
NOMBRE,APELLIDO y Tercera letra del nombre = a*/

SELECT E.FIRST_NAME, 
       E.LAST_NAME, 
       C.COUNTRY_NAME
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID
JOIN HR.COUNTRIES C
    ON L.COUNTRY_ID = C.COUNTRY_ID
WHERE C.COUNTRY_NAME = 'United Kingdom'
  AND E.FIRST_NAME LIKE '__a%';
  
/*7. TRAER TODOS LOS EMPLEADOS CUYA COMISION SEA DIFERENTE A NULO
NOMBRE EMPLEADO + COMISION*/

SELECT E.FIRST_NAME, 
       E.COMMISSION_PCT
FROM HR.EMPLOYEES E
WHERE E.COMMISSION_PCT IS NOT NULL;

//8.BUSCAR LA SUMA DE TODOS LOS SALARIOS,CUAL ES EL SALRIO MAXIMO,MIN DE TODOS Y DESVIACION ESTANDAR
SELECT 
    SUM(E.SALARY) AS "SUMA_TOTAL_SALARIOS",
    MAX(E.SALARY) AS "SALARIO_MAXIMO",
    MIN(E.SALARY) AS "SALARIO_MINIMO",
    STDDEV(E.SALARY) AS "DESVIACION_ESTANDAR"
FROM HR.EMPLOYEES E;

/*9.TRAER NOMBRE EMPLEADO,TRAER SALARIO,COMPARAR LOS SALARIO
SI EL SALARIO ES MENOR A 1000 DOLARES SALDRA UN TEXTO
'POBRECITO'
SI ES MENOS A 3000 DOLARES SALDRA
'SIGUE INTENTANDO'
SI ES MENOR A 5000 DOLARES SALDRA
'YA CASI'
SI ES MAYOR A 10000 DOLARES SALDRA
'INGENIEROS'
Y SI ES OTRO VALOR SALDRA 'OTROS' */

SELECT
first_name AS nombre_empleado,
salary AS salario,
CASE
WHEN salary < 1000 THEN 'pobrecito'
WHEN salary < 3000 THEN 'sigue intentándolo'
WHEN salary < 5000 THEN 'ya casi'
WHEN salary > 10000 THEN 'buenos días ingeniero'
ELSE 'otros'
END AS mensaje
FROM HR.EMPLOYEES;

// 10.MOSTRAR TODOS LOS SALARIOS CUYO SLARIO SEA MAYOR AL PROMEDIO DE SU DEPARTAMENTO,TRAER NOMBRE DEPTO,SALARIO,NOMBRE EMPLEADO,PROMEDIO

SELECT E.LAST_NAME, 
       E.SALARY,
       ROUND((SELECT AVG(ED.SALARY) 
       
FROM HR.EMPLOYEES ED 
WHERE ED.DEPARTMENT_ID = E.DEPARTMENT_ID)) AS "PROM_DEPTO"
FROM HR.EMPLOYEES E
WHERE E.SALARY > (SELECT AVG(ED.SALARY) 
                 FROM HR.EMPLOYEES ED 
                    WHERE ED.DEPARTMENT_ID = E.DEPARTMENT_ID);

/*11.
UNA EMPRESA DESEA IDENTIFICAR EMPLEADOS QUE CUMPLAN SIMULTANEAMENTE ES DECIR TRODAS LAS CONDICIONES
SU SALARIO ES MAYOR AL PROMEDIO DE SU DEPARTAMENTO
2.FUERON CONTRATADOS DESPUES DEL EMPLEADO MAS ANTIGUO DE SU DEPARTAMENTO
NO TIENEN SUB-ORDINADOS DIRECTOS
SU SALARIO ES INFERIOR AL SALARIO MAXIMO DE SU DEPARTAMENTO*/

SELECT E.EMPLOYEE_ID, 
       E.FIRST_NAME, 
       E.LAST_NAME, 
       E.SALARY, 
       E.HIRE_DATE, 
       E.DEPARTMENT_ID
FROM HR.EMPLOYEES E
WHERE E.SALARY > (
        SELECT AVG(SUB.SALARY)
        FROM HR.EMPLOYEES SUB
        WHERE SUB.DEPARTMENT_ID = E.DEPARTMENT_ID
    )
    AND E.HIRE_DATE > (
        SELECT MIN(SUB.HIRE_DATE)
        FROM HR.EMPLOYEES SUB
        WHERE SUB.DEPARTMENT_ID = E.DEPARTMENT_ID
    )
    AND NOT EXISTS (
        SELECT 1
        FROM HR.EMPLOYEES MGR
        WHERE MGR.MANAGER_ID = E.employee_id
    )
    AND E.SALARY < (
        SELECT MAX(SUB.SALARY)
        FROM HR.EMPLOYEES SUB
        WHERE SUB.DEPARTMENT_ID = E.DEPARTMENT_ID
    );